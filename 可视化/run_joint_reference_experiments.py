"""Run the coarse B3 joint reference on a declared paired subset."""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import asdict
from pathlib import Path

import numpy as np

from experiment_cases import CASE_KINDS, generate_case
from experiment_methods import JOINT_REFERENCE, method_by_key, run_method
from experiment_metrics import bootstrap_paired_difference, evaluate_run, exact_mcnemar
from joint_reference import JointGrid
from run_randomized_experiments import RAW_FIELDS


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "小论文-2" / "generated"
SUBSET_METHODS = (JOINT_REFERENCE, method_by_key("MIKU"))


def _write_csv(path: Path, rows: list[dict], fields: tuple[str, ...]) -> None:
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def _finite_mean(rows: list[dict], key: str) -> float | None:
    values = np.asarray(
        [row[key] for row in rows if row.get(key) is not None], dtype=float
    )
    values = values[np.isfinite(values)]
    return float(values.mean()) if values.size else None


def _summaries(rows: list[dict]) -> list[dict]:
    summaries = []
    for method in SUBSET_METHODS:
        subset = [row for row in rows if row["method"] == method.key]
        runtime = np.asarray([row["runtime_ms"] for row in subset], dtype=float)
        summaries.append(
            {
                "method": method.key,
                "n": len(subset),
                "success_rate": _finite_mean(subset, "success"),
                "collision_rate": _finite_mean(subset, "collision"),
                "min_clearance_mean_m": _finite_mean(subset, "min_clearance_m"),
                "progress_ratio_mean": _finite_mean(subset, "progress_ratio"),
                "penalized_travel_time_mean_s": _finite_mean(
                    subset, "penalized_travel_time_s"
                ),
                "runtime_p50_ms": float(np.quantile(runtime, 0.50)),
                "runtime_p95_ms": float(np.quantile(runtime, 0.95)),
            }
        )
    return summaries


def _paired(rows: list[dict]) -> list[dict]:
    indexed = {
        (row["case_kind"], row["seed"], row["method"]): row for row in rows
    }
    keys = sorted({(row["case_kind"], row["seed"]) for row in rows})
    statistics = []
    for index, metric in enumerate(
        ("success", "collision", "min_clearance_m", "penalized_travel_time_s")
    ):
        miku = np.asarray([indexed[(*key, "MIKU")][metric] for key in keys], dtype=float)
        b3 = np.asarray([indexed[(*key, "B3")][metric] for key in keys], dtype=float)
        result = bootstrap_paired_difference(miku, b3, seed=93000 + index)
        if metric in ("success", "collision"):
            result.update(exact_mcnemar(miku, b3))
        else:
            result.update(
                {
                    "candidate_only": None,
                    "reference_only": None,
                    "discordant": None,
                    "mcnemar_exact_p": None,
                }
            )
        statistics.append(
            {
                "comparison": "MIKU-B3",
                "metric": metric,
                **result,
            }
        )
    return statistics


def _macros(summaries: list[dict], paired: list[dict], rows: list[dict]) -> str:
    by_method = {row["method"]: row for row in summaries}
    by_metric = {row["metric"]: row for row in paired}
    b3 = by_method["B3"]
    miku = by_method["MIKU"]
    success = by_metric["success"]
    indexed = {
        (row["case_kind"], row["seed"], row["method"]): row for row in rows
    }
    keys = sorted({(row["case_kind"], row["seed"]) for row in rows})
    b3_only_successes = sum(
        int(indexed[(*key, "B3")]["success"])
        and not int(indexed[(*key, "MIKU")]["success"])
        for key in keys
    )
    miku_only_successes = sum(
        int(indexed[(*key, "MIKU")]["success"])
        and not int(indexed[(*key, "B3")]["success"])
        for key in keys
    )
    return "\n".join(
        (
            "% Auto-generated by run_joint_reference_experiments.py; do not edit.",
            f"\\newcommand{{\\JointCaseCount}}{{{b3['n']}}}",
            f"\\newcommand{{\\JointBThreeSuccessPct}}{{{100*b3['success_rate']:.1f}}}",
            f"\\newcommand{{\\JointMikuSuccessPct}}{{{100*miku['success_rate']:.1f}}}",
            f"\\newcommand{{\\JointBThreeCollisionPct}}{{{100*b3['collision_rate']:.1f}}}",
            f"\\newcommand{{\\JointMikuCollisionPct}}{{{100*miku['collision_rate']:.1f}}}",
            f"\\newcommand{{\\JointBThreeRuntimePninetyfive}}{{{b3['runtime_p95_ms']:.2f}}}",
            f"\\newcommand{{\\JointMikuRuntimePninetyfive}}{{{miku['runtime_p95_ms']:.2f}}}",
            f"\\newcommand{{\\JointMikuVsBThreeSuccessDiff}}{{{100*success['mean_difference']:.1f}}}",
            f"\\newcommand{{\\JointMikuVsBThreeSuccessCiLow}}{{{100*success['ci_low']:.1f}}}",
            f"\\newcommand{{\\JointMikuVsBThreeSuccessCiHigh}}{{{100*success['ci_high']:.1f}}}",
            f"\\newcommand{{\\JointMikuVsBThreeSuccessMcNemarP}}{{{success['mcnemar_exact_p']:.4g}}}",
            f"\\newcommand{{\\JointBThreeOnlySuccessCount}}{{{b3_only_successes}}}",
            f"\\newcommand{{\\JointMikuOnlySuccessCount}}{{{miku_only_successes}}}",
            "",
        )
    )


def run(seed_start: int, seed_count: int, output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    for kind in CASE_KINDS:
        for seed in range(seed_start, seed_start + seed_count):
            case = generate_case(kind, seed)
            for method in SUBSET_METHODS:
                row = evaluate_run(run_method(method, case.planning_scenario), case)
                row["schema_version"] = "miku-joint-reference-v1"
                rows.append(row)
        print(f"completed joint subset: {kind}", flush=True)
    summaries = _summaries(rows)
    paired = _paired(rows)
    _write_csv(output / "joint_reference_raw.csv", rows, RAW_FIELDS)
    _write_csv(
        output / "joint_reference_summary.csv", summaries, tuple(summaries[0])
    )
    _write_csv(
        output / "joint_reference_paired.csv", paired, tuple(paired[0])
    )
    (output / "joint_reference_macros.tex").write_text(
        _macros(summaries, paired, rows), encoding="utf-8"
    )
    metadata = {
        "protocol": "miku-joint-reference-v1",
        "case_kinds": list(CASE_KINDS),
        "seed_start": seed_start,
        "seed_count_per_kind": seed_count,
        "paired_case_count": len(CASE_KINDS) * seed_count,
        "grid": asdict(JointGrid()),
        "scope": "Deterministic beam search on a coarse joint grid; not a continuous global optimum.",
        "summaries": summaries,
        "paired_statistics": paired,
    }
    (output / "joint_reference_results.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed-start", type=int, default=0)
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    if args.seed_start < 0 or args.seeds <= 0:
        parser.error("--seed-start must be non-negative and --seeds must be positive")
    run(args.seed_start, args.seeds, args.output)


if __name__ == "__main__":
    main()
