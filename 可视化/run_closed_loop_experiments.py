"""Run rolling-horizon paired experiments for all four main methods."""

from __future__ import annotations

import argparse
import csv
import json
from dataclasses import asdict
from pathlib import Path

import numpy as np

from closed_loop import ClosedLoopConfig, run_closed_loop
from experiment_cases import CASE_KINDS, generate_case
from experiment_methods import METHODS
from experiment_metrics import bootstrap_paired_difference, evaluate_run, exact_mcnemar
from run_randomized_experiments import RAW_FIELDS


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "小论文-2" / "generated"
CLOSED_LOOP_FIELDS = (*RAW_FIELDS, "planning_cycles")


def _write_csv(path: Path, rows: list[dict], fields: tuple[str, ...]) -> None:
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def _mean(rows: list[dict], key: str) -> float:
    values = np.asarray([row[key] for row in rows], dtype=float)
    return float(values[np.isfinite(values)].mean())


def _summaries(rows: list[dict]) -> list[dict]:
    summaries = []
    for method in METHODS:
        subset = [row for row in rows if row["method"] == method.key]
        runtime = np.asarray([row["runtime_ms"] for row in subset], dtype=float)
        summaries.append(
            {
                "method": method.key,
                "n": len(subset),
                "success_rate": _mean(subset, "success"),
                "collision_rate": _mean(subset, "collision"),
                "degraded_stop_rate": _mean(subset, "degraded_stop"),
                "min_clearance_mean_m": _mean(subset, "min_clearance_m"),
                "progress_ratio_mean": _mean(subset, "progress_ratio"),
                "penalized_travel_time_mean_s": _mean(
                    subset, "penalized_travel_time_s"
                ),
                "planning_cycles_mean": _mean(subset, "planning_cycles"),
                "episode_runtime_p50_ms": float(np.quantile(runtime, 0.50)),
                "episode_runtime_p95_ms": float(np.quantile(runtime, 0.95)),
            }
        )
    return summaries


def _paired(rows: list[dict]) -> list[dict]:
    indexed = {
        (row["case_kind"], row["seed"], row["method"]): row for row in rows
    }
    keys = sorted({(row["case_kind"], row["seed"]) for row in rows})
    statistics = []
    for baseline_index, baseline in enumerate(METHODS[:-1]):
        for metric_index, metric in enumerate(("success", "collision")):
            miku = np.asarray(
                [indexed[(*key, "MIKU")][metric] for key in keys], dtype=float
            )
            comparison = np.asarray(
                [indexed[(*key, baseline.key)][metric] for key in keys], dtype=float
            )
            result = bootstrap_paired_difference(
                miku,
                comparison,
                seed=94000 + baseline_index * 10 + metric_index,
            )
            result.update(exact_mcnemar(miku, comparison))
            statistics.append(
                {
                    "comparison": f"MIKU-{baseline.key}",
                    "metric": metric,
                    **result,
                }
            )
    return statistics


def _macros(summaries: list[dict], paired: list[dict]) -> str:
    by_method = {row["method"]: row for row in summaries}
    success = next(
        row
        for row in paired
        if row["comparison"] == "MIKU-B0" and row["metric"] == "success"
    )
    collision = next(
        row
        for row in paired
        if row["comparison"] == "MIKU-B0" and row["metric"] == "collision"
    )
    lines = [
        "% Auto-generated by run_closed_loop_experiments.py; do not edit.",
        f"\\newcommand{{\\ClosedCaseCount}}{{{by_method['MIKU']['n']}}}",
    ]
    for method, word in (("B0", "BZero"), ("B1", "BOne"), ("B2", "BTwo"), ("MIKU", "Miku")):
        row = by_method[method]
        lines.extend(
            (
                f"\\newcommand{{\\Closed{word}SuccessPct}}{{{100*row['success_rate']:.1f}}}",
                f"\\newcommand{{\\Closed{word}CollisionPct}}{{{100*row['collision_rate']:.1f}}}",
                f"\\newcommand{{\\Closed{word}RuntimePninetyfive}}{{{row['episode_runtime_p95_ms']:.2f}}}",
            )
        )
    lines.extend(
        (
            f"\\newcommand{{\\ClosedMikuVsBZeroSuccessDiff}}{{{100*success['mean_difference']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroSuccessCiLow}}{{{100*success['ci_low']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroSuccessCiHigh}}{{{100*success['ci_high']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroSuccessMcNemarP}}{{{success['mcnemar_exact_p']:.4g}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroCollisionDiff}}{{{100*collision['mean_difference']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroCollisionCiLow}}{{{100*collision['ci_low']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroCollisionCiHigh}}{{{100*collision['ci_high']:.1f}}}",
            f"\\newcommand{{\\ClosedMikuVsBZeroCollisionMcNemarP}}{{{collision['mcnemar_exact_p']:.4g}}}",
            "",
        )
    )
    return "\n".join(lines)


def run(seed_start: int, seed_count: int, output: Path) -> None:
    output.mkdir(parents=True, exist_ok=True)
    config = ClosedLoopConfig()
    rows = []
    for kind in CASE_KINDS:
        for seed in range(seed_start, seed_start + seed_count):
            case = generate_case(kind, seed)
            for method in METHODS:
                method_run = run_closed_loop(method, case, config)
                row = evaluate_run(method_run, case)
                row["schema_version"] = "miku-rolling-v1"
                row["planning_cycles"] = method_run.result["closed_loop_cycles"]
                rows.append(row)
        print(f"completed rolling subset: {kind}", flush=True)

    summaries = _summaries(rows)
    paired = _paired(rows)
    _write_csv(output / "closed_loop_raw.csv", rows, CLOSED_LOOP_FIELDS)
    _write_csv(output / "closed_loop_summary.csv", summaries, tuple(summaries[0]))
    _write_csv(output / "closed_loop_paired.csv", paired, tuple(paired[0]))
    (output / "closed_loop_macros.tex").write_text(
        _macros(summaries, paired), encoding="utf-8"
    )
    metadata = {
        "protocol": "miku-rolling-v1",
        "case_kinds": list(CASE_KINDS),
        "seed_start": seed_start,
        "seed_count_per_kind": seed_count,
        "paired_case_count": len(CASE_KINDS) * seed_count,
        "methods": [method.key for method in METHODS],
        "config": asdict(config),
        "execution": "Execute the first 0.5 s segment, update ego/obstacles, and replan until arrival or scenario horizon.",
        "noise": "The initial observation biases are held fixed across replans; execution applies planned increments to truth state.",
        "summaries": summaries,
        "paired_statistics": paired,
    }
    (output / "closed_loop_results.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed-start", type=int, default=0)
    parser.add_argument("--seeds", type=int, default=10)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    if args.seed_start < 0 or args.seeds <= 0:
        parser.error("--seed-start must be non-negative and --seeds must be positive")
    run(args.seed_start, args.seeds, args.output)


if __name__ == "__main__":
    main()
